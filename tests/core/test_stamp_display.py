from timetoalign.timelines import Timeline, TimelineGroup

FM = TimeUnit.floating_measures


def _clock(uid: str = "clock") -> Timeline:
    """A 100-second timeline with a milliseconds, a frames and a label map.

    The frames map covers ``[0, 50]`` seconds only and refuses beyond it.
    """
    timeline = Timeline(length=100, unit=TimeUnit.seconds, uid=uid)
    timeline.add_conversion_map(
        TableMap(
            x_values=[0.0, 100.0],
            y_values=[0.0, 100000.0],
            source_unit=TimeUnit.seconds,
            target_unit=TimeUnit.milliseconds,
            uid=f"{uid}-ms",
        )
    )
    timeline.add_conversion_map(
        TableMap(
            x_values=[0.0, 50.0],
            y_values=[0.0, 2500.0],
            source_unit=TimeUnit.seconds,
            target_unit=TimeUnit.frames,
            extrapolate="error",
            uid=f"{uid}-frames",
        )
    )
    timeline.add_conversion_map(
        IntervalToConstantMap(
            boundaries=[0, 20, 60],
            values=["intro", "verse", "coda"],
            source_unit=TimeUnit.seconds,
            uid=f"{uid}-sections",
            name="section",
        )
    )
    return timeline


def _with_children() -> Timeline:
    """The clock with a child ``intro`` at 0 and ``verse`` at 20 seconds."""
    clock = _clock()
    clock.add_child(Timeline(length=30, unit=TimeUnit.seconds, uid="intro"), 0)
    clock.add_child(Timeline(length=40, unit=TimeUnit.seconds, uid="verse"), 20)
    return clock


def _score() -> Timeline:
    """A fraction-canonical score with a ticks map and a child at 8/3."""
    score = Timeline(length=40, unit=TimeUnit.quarters, uid="score")
    score.add_conversion_map(
        LinearMap(
            scalar=480,
            source_unit=TimeUnit.quarters,
            target_unit=TimeUnit.ticks,
            uid="score-ticks",
        )
    )
    score.add_child(
        Timeline(length=Fraction(20, 3), unit=TimeUnit.quarters, uid="bar"),
        Fraction(8, 3),
    )
    return score


def _fm_coordinate(value: float) -> Coordinate:
    return Coordinate(value, FM, number_type=NumberType.float)


def _interval_claim(
    a: str, start_a: float, end_a: float, b: str, start_b: float, end_b: float
) -> MatchClaim:
    return match_claim(
        a,
        _fm_coordinate(start_a),
        b,
        _fm_coordinate(start_b),
        end_a=_fm_coordinate(end_a),
        end_b=_fm_coordinate(end_b),
    )


def _interval_bundle(
    *claims: MatchClaim, timelines: tuple[str, ...]
) -> AlignmentBundle:
    bundle = AlignmentBundle(id="interval-display")
    for uid in timelines:
        bundle.add_timeline(
            Timeline(length=200, uid=uid, unit=FM, number_type=NumberType.float)
        )
    bundle.add_match_claims(list(claims))
    return bundle


def _display_stamps() -> dict[str, Stamp]:
    """The stamps whose displays are compared, by name."""
    stamps: dict[str, Stamp] = {}
    stamps["timestamp_children_and_maps"] = _with_children().get_timestamp(25.0)
    stamps["timestamp_outside_a_map"] = _with_children().get_timestamp(70.0)
    stamps["timestamp_without_maps"] = _with_children().get_timestamp_at(
        25.0, conversion_maps=False
    )
    stamps["timestamp_exact"] = _score().get_timestamp(Fraction(19, 2))
    stamps["timestamp_interpolated"] = TimeStamp(
        coordinates={
            "audio": Coordinate(1.25, TimeUnit.seconds),
            "frames": Coordinate(30, TimeUnit.frames),
            "score": Coordinate(Fraction(7, 3), TimeUnit.quarters),
        },
        source_id="audio",
        is_interpolated=True,
    )
    group = TimelineGroup(id="pair", timelines=[_clock("left"), _clock("right")])
    stamps["timestamp_group_colliding_labels"] = group.get_timestamp_at(10.0, "left")

    bundle = AlignmentBundle(id="stamp-display")
    bundle.add_timeline(_clock(), as_group="clock-group")
    stamps["matchstamp_bundle_maps"] = bundle.get_matchstamp_at(
        25.0, "clock", conversion_maps=True
    )
    stamps["matchstamp_bundle_no_maps"] = bundle.get_matchstamp_at(25.0, "clock")
    stamps["matchstamp_tags"] = MatchStamp(
        coordinates={
            "score": Coordinate(4, TimeUnit.quarters),
            "parts": Coordinate(Fraction(9, 2), TimeUnit.quarters),
            "audio": Coordinate(2.5, TimeUnit.seconds),
            "image": Coordinate(1200, TimeUnit.pixels),
        },
        source_id="score",
        stated_pairs=[("score", "audio")],
        inferred_pairs=[("score", "parts")],
        is_interpolated=True,
    )
    stamps["matchstamp_crossfade"] = _interval_bundle(
        _interval_claim("mix", 125, 135, "track-a", 33, 43),
        _interval_claim("mix", 128, 138, "track-b", 1, 11),
        timelines=("mix", "track-a", "track-b"),
    ).get_matchstamp_at(130, "mix")
    stamps["matchstamp_loop_ambiguity"] = _interval_bundle(
        _interval_claim("mix", 10, 20, "loop", 0, 10),
        _interval_claim("mix", 20, 30, "loop", 100, 110),
        timelines=("mix", "loop"),
    ).get_matchstamp_at(20, "mix")
    stamps["matchstamp_missing_counterpart"] = _interval_bundle(
        _interval_claim("mix", 10, 10, "track", 30, 40),
        timelines=("mix", "track"),
    ).get_matchstamp_at(10, "mix")
    return stamps


