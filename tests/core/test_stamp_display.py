def _raise_boom(*args: object, **kwargs: object) -> None:
    raise RuntimeError("boom")


def _statement(excinfo: pytest.ExceptionInfo[RuntimeError], frame: str) -> str:
    """The statement the traceback passes through in *frame*, on one line."""
    (entry,) = [entry for entry in excinfo.traceback if entry.name == frame]
    return " ".join(str(entry.statement).split())


def _timestamp_at(position: float) -> Stamp:
    return _clock().get_timestamp(position)


def _matchstamp_at(position: float) -> Stamp:
    bundle = AlignmentBundle(id="stamp-errors")
    bundle.add_timeline(_clock(), as_group="clock-group")
    return bundle.get_matchstamp_at(position, "clock", conversion_maps=True)


class TestUnexpectedErrorsPropagate:
    """A C-Map row is left out only where the map does not reach the stamp."""

    @pytest.mark.parametrize("make", [_timestamp_at, _matchstamp_at])
    def test_a_failing_map_propagates_from_the_rows(
        self, make, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        stamp = make(25.0)
        monkeypatch.setattr(TableMap, "_evaluate", _raise_boom)

        with pytest.raises(RuntimeError, match="^boom$") as excinfo:
            str(stamp)
        assert _statement(excinfo, "_conversion_rows") == (
            "value = cmap._evaluate(coordinate.value)"
        )

    def test_a_map_not_reaching_a_timestamp_leaves_its_row_out(self) -> None:
        assert str(_timestamp_at(25.0)) == (
            "TimeStamp @25 seconds\n"
            "  clock         25 seconds\n"
            "  milliseconds  25000 milliseconds\n"
            "  frames        1250 frames\n"
            "  section       verse"
        )
        assert str(_timestamp_at(70.0)) == (
            "TimeStamp @70 seconds\n"
            "  clock         70 seconds\n"
            "  milliseconds  70000 milliseconds\n"
            "  section       coda"
        )

    def test_a_map_not_reaching_a_matchstamp_leaves_its_row_out(self) -> None:
        assert str(_matchstamp_at(25.0)) == (
            "MatchStamp (1 timelines, 0 edges)\n"
            "  clock                 25 seconds\n"
            "  milliseconds  25000 milliseconds\n"
            "  frames               1250 frames\n"
            "  section                    verse"
        )
        assert str(_matchstamp_at(70.0)) == (
            "MatchStamp (1 timelines, 0 edges)\n"
            "  clock                 70 seconds\n"
            "  milliseconds  70000 milliseconds\n"
            "  section                     coda"
        )
